#ifndef LEAFTL_MEMORY_H_
#define LEAFTL_MEMORY_H_
#include <stddef.h>
#include <stdint.h>
#include "leaftl_mapping.h"
#include "leaftl_writeback.h"
#include "leaftl_flash.h"
#include "leaftl_cache.h"
#include "leaftl_metadata.h"

#define LEAFTL_RAM_ALIGNMENT 64U
#define LEAFTL_RAM_ALIGN(value) (((uint64_t)(value)+63ULL)&~63ULL)
#define LEAFTL_RAM_CONTEXT_OFFSET 0ULL
#define LEAFTL_RAM_INDEX_OFFSET LEAFTL_RAM_ALIGN(sizeof(LEAFTL_MAPPING))
#define LEAFTL_RAM_GROUPS_OFFSET LEAFTL_RAM_ALIGN(LEAFTL_RAM_INDEX_OFFSET+sizeof(LEAFTL_INDEX))
#define LEAFTL_RAM_LEVELS_OFFSET LEAFTL_RAM_ALIGN(LEAFTL_RAM_GROUPS_OFFSET+ \
    (uint64_t)LEAFTL_MAX_CACHED_GROUPS*sizeof(LEAFTL_INDEX_GROUP))
#define LEAFTL_RAM_NODES_OFFSET LEAFTL_RAM_ALIGN(LEAFTL_RAM_LEVELS_OFFSET+ \
    (uint64_t)LEAFTL_RESIDENT_LEVEL_CAPACITY*sizeof(LEAFTL_INDEX_LEVEL))
#define LEAFTL_RAM_WORKSPACE_OFFSET LEAFTL_RAM_ALIGN(LEAFTL_RAM_NODES_OFFSET+ \
    (uint64_t)LEAFTL_MAX_RESIDENT_SEGMENTS*sizeof(LEAFTL_INDEX_NODE))
#define LEAFTL_RAM_POINTS_OFFSET LEAFTL_RAM_ALIGN(LEAFTL_RAM_WORKSPACE_OFFSET+sizeof(LEAFTL_INDEX_WORKSPACE))
#define LEAFTL_RAM_INPUTS_OFFSET LEAFTL_RAM_ALIGN(LEAFTL_RAM_POINTS_OFFSET+ \
    (uint64_t)LEAFTL_MAX_TRAINING_POINTS*sizeof(LEAFTL_TRAINING_POINT))
#define LEAFTL_RAM_WRITEBACK_OFFSET LEAFTL_RAM_ALIGN(LEAFTL_RAM_INPUTS_OFFSET+ \
    (uint64_t)LEAFTL_MAX_TRAINING_POINTS*sizeof(LEAFTL_SEGMENT_INPUT))
#define LEAFTL_RAM_GC_WORK_OFFSET LEAFTL_RAM_ALIGN(LEAFTL_RAM_WRITEBACK_OFFSET+sizeof(LEAFTL_WRITEBACK_WORK))
#define LEAFTL_RAM_FLASH_CONTEXT_OFFSET LEAFTL_RAM_ALIGN(LEAFTL_RAM_GC_WORK_OFFSET+sizeof(LEAFTL_WRITEBACK_WORK))
#define LEAFTL_RAM_CACHE_OFFSET LEAFTL_RAM_ALIGN(LEAFTL_RAM_FLASH_CONTEXT_OFFSET+sizeof(LEAFTL_FLASH))
#define LEAFTL_RAM_METADATA_OFFSET LEAFTL_RAM_ALIGN(LEAFTL_RAM_CACHE_OFFSET+sizeof(LEAFTL_CACHE))
#define LEAFTL_RAM_METADATA_BLOCKS_OFFSET LEAFTL_RAM_ALIGN(LEAFTL_RAM_METADATA_OFFSET+sizeof(LEAFTL_METADATA))
/* Match the existing reserved translation pool; no new data blocks reserved. */
#define LEAFTL_METADATA_BLOCK_CAPACITY 64U
#define LEAFTL_RAM_DIRECTORY_OFFSET LEAFTL_RAM_ALIGN(LEAFTL_RAM_METADATA_BLOCKS_OFFSET+ \
    LEAFTL_METADATA_BLOCK_CAPACITY*sizeof(LEAFTL_METADATA_BLOCK))
#define LEAFTL_RAM_DIRECTORY_BYTES(lpn_count) \
    ((uint64_t)LEAFTL_GROUP_COUNT(lpn_count)*LEAFTL_DIRECTORY_ENTRY_RESERVED_BYTES)
#define LEAFTL_RAM_BYTES(lpn_count) LEAFTL_RAM_ALIGN(LEAFTL_RAM_DIRECTORY_OFFSET+ \
    LEAFTL_RAM_DIRECTORY_BYTES(lpn_count))

typedef char LeaFtlLevelPoolValid[(LEAFTL_RESIDENT_LEVEL_CAPACITY>0U &&
    (uint64_t)LEAFTL_RESIDENT_LEVEL_CAPACITY<=UINT_MAX &&
    (uint64_t)LEAFTL_RESIDENT_LEVEL_CAPACITY<=
        (uint64_t)LEAFTL_MAX_CACHED_GROUPS*LEAFTL_MAX_LEVELS_PER_GROUP) ? 1 : -1];
typedef char LeaFtlFixedRamFits[(LEAFTL_RAM_DIRECTORY_OFFSET<=LEAFTL_METADATA_RAM_BUDGET_BYTES) ? 1 : -1];
typedef char LeaFtlFlushPoolValid[(LEAFTL_FLUSH_SORT_CAPACITY>0U) ? 1 : -1];
typedef char LeaFtlDirectoryReservationValid[(sizeof(LEAFTL_FLASH_DIRECTORY_ENTRY)==LEAFTL_DIRECTORY_ENTRY_RESERVED_BYTES)?1:-1];

/* Bind/initialize in supplied aligned RAM; does not allocate or touch NAND.
 * Initializes the typed directory to absent and clears the flash context;
 * NAND callbacks are bound at step 12. All argument validation precedes writes. Result must be
 * disjoint from the arena. Call explicitly at later firmware integration.
 */
LEAFTL_MAPPING_STATUS LeaFtlMemoryInit(void *arena,size_t arena_bytes,
    unsigned int logical_count,LEAFTL_MAPPING **result);
#endif
